_entity_emb_cache = {"node_ids": None, "embeddings": None}

def _build_entity_embeddings():
    """Считает эмбеддинги имён всех Entity-узлов графа. Кэшируется."""
    embedder = get_embedder()
    node_ids, names = [], []
    for node_id, data in graph.nodes(data=True):
        if data.get("type") == "Entity":
            name = data.get("name", "")
            if name:
                node_ids.append(node_id)
                names.append(name)
    if not node_ids:
        _entity_emb_cache["node_ids"] = []
        _entity_emb_cache["embeddings"] = None
        return
    embs = embedder.encode(
        [f"passage: {n}" for n in names], normalize_embeddings=True
    )
    _entity_emb_cache["node_ids"] = node_ids
    _entity_emb_cache["embeddings"] = embs
    print(f"  [граф] эмбеддинги {len(node_ids)} Entity-узлов посчитаны")

# поиск статей-кандидатов через граф по эмбэнддингам
def find_candidate_articles(question, top_entities=15, max_articles=3,
                            dominance_ratio=1.6):
    """
    По вопросу находит статьи-кандидаты через граф (по эмбеддингам)

    Адаптивное сужение:
      - если топ-1 статья доминирует (её вес в dominance_ratio раз
        больше веса следующей) - возвращаем только её (адресный вопрос)
      - иначе возвращаем группу статей с близкими весами
        (связующий вопрос, ответ в нескольких статьях)

    возвращает список имён статей (source), ранжированный
    пустой список = граф не смог сузить.
    """
    import numpy as np
    from collections import defaultdict

    if _entity_emb_cache["node_ids"] is None:
        _build_entity_embeddings()
    node_ids = _entity_emb_cache["node_ids"]
    entity_embs = _entity_emb_cache["embeddings"]
    if not node_ids or entity_embs is None:
        return []

    embedder = get_embedder()
    q_emb = embedder.encode(f"query: {question}", normalize_embeddings=True)
    sims = np.dot(entity_embs, q_emb)
    top_idx = np.argsort(sims)[::-1][:top_entities]

    # накапливаем вес каждой статьи
    article_score = defaultdict(float)
    for idx in top_idx:
        node_id = node_ids[idx]
        weight = float(sims[idx])
        for _, part_id, edge in graph.out_edges(node_id, data=True):
            if edge.get("type") != "mentioned_in":
                continue
            source = graph.nodes.get(part_id, {}).get("source")
            if source:
                article_score[source] += weight

    if not article_score:
        return []

    ranked = sorted(article_score.items(), key=lambda x: x[1], reverse=True)

    # адаптивное решение, сколько статей вернуть
    if len(ranked) == 1:
        return [ranked[0][0]]

    top_score = ranked[0][1]
    second_score = ranked[1][1]

    # Если топ-1 доминирует — это адресный вопрос, берём одну статью
    if second_score > 0 and top_score / second_score >= dominance_ratio:
        return [ranked[0][0]]

    # иначе связующий вопрос берём группу статей с близкими весами
    # оставляем те, чей вес не меньше половины веса лидера
    group = [src for src, sc in ranked[:max_articles]
             if sc >= top_score * 0.5]
    return group


# векторный поиск с фильтром по статьям
def vector_search_filtered(query, allowed_sources=None, top_k=TOP_K_VECTOR):
    """
    Векторный поиск с опциональным ограничением по статьям.
    Если allowed_sources задан - ищем только в чанках этих статей
    (через фильтр ChromaDB по метаданным). Иначе - по всему корпусу.
    """
    embedder = get_embedder()
    query_embedding = embedder.encode(
        f"query: {query}", normalize_embeddings=True
    ).tolist()

    # фильтр ChromaDB по полю source в метаданных
    where_filter = None
    if allowed_sources:
        if len(allowed_sources) == 1:
            where_filter = {"source": allowed_sources[0]}
        else:
            where_filter = {"source": {"$in": allowed_sources}}

    results = collection.query(
        query_embeddings=[query_embedding],
        n_results=top_k,
        where=where_filter,
    )

    found = []
    for i in range(len(results["ids"][0])):
        found.append({
            "text": results["documents"][0][i],
            "metadata": results["metadatas"][0][i],
            "distance": results["distances"][0][i],
        })
    return found


# гибридный RAG v2: граф расширяет поиск, не режет
def hybrid_rag(question, top_k_vec=TOP_K_VECTOR, top_k_graph=TOP_K_GRAPH,
               graph_extra=3, verbose=True):
    """
    Гибридный ретривер v2 (расширяющий)

    Принцип: граф не заменяет и не сужает векторный поиск, а дополняет его
      1) базовый векторный поиск по всему корпусу (как vanilla)
      2) граф находит статьи-кандидаты по сущностям вопроса
      3) дополнительный векторный поиск ВНУТРИ графовых статей
      4) объединяем чанки (базовые + графовые, без дублей)
      5) добавляем semantic_link triplet'ы графа в контекст

    Так hybrid всегда имеет как минимум то же, что vanilla, плюс
    графовое расширение - и не может оказаться хуже baseline

    graph_extra - сколько дополнительных чанков добирать через граф.
    """
    # 1) базовый векторный поиск по всему корпусу
    base_chunks = vector_search_filtered(question, None, top_k=top_k_vec)

    # 2) сущности запроса и статьи-кандидаты через граф
    query_entities, query_rels = extract_query_entities(question)
    candidate_articles = find_candidate_articles(question)

    # 3) дополнительный поиск внутри графовых статей
    # граф подсказал статьи - добираем оттуда ещё чанков
    graph_chunks = []
    if candidate_articles:
        graph_chunks = vector_search_filtered(
            question, candidate_articles, top_k=graph_extra
        )

    # 4) объединяем базовые и графовые чанки, убираем дубли по тексту
    seen_texts = set()
    merged_chunks = []
    for ch in base_chunks + graph_chunks:
        if ch["text"] not in seen_texts:
            seen_texts.add(ch["text"])
            merged_chunks.append(ch)

    # 5) триплеты графа
    triplets = find_graph_triplets(query_entities, max_triplets=top_k_graph)

    # сборка контекста: триплеты графа сверху, затем чанки
    text_context = format_context(merged_chunks)
    graph_context = format_graph_triplets(triplets)
    if graph_context:
        full_context = graph_context + "\n\n" + text_context
    else:
        full_context = text_context

    if not merged_chunks and not triplets:
        answer = "I could not find the answer in the indexed materials."
    else:
        response = rag_chain.invoke({"context": full_context, "question": question})
        answer = response.content.strip()

    # источники
    sources = []
    seen = set()
    for ch in merged_chunks:
        key = (ch["metadata"]["source"], ch["metadata"]["part_heading"])
        if key not in seen:
            seen.add(key)
            sources.append({
                "source": ch["metadata"]["source"],
                "section": ch["metadata"]["part_heading"],
                "distance": ch["distance"],
            })

    if verbose:
        print(f"Вопрос: {question}\n")
        print(f"Сущности из запроса ({len(query_entities)}): {query_entities}")
        print(f"Статьи-кандидаты от графа: {candidate_articles}")
        print(f"Базовых чанков: {len(base_chunks)}, графовых добавлено: "
              f"{len(merged_chunks) - len(base_chunks)}, всего: {len(merged_chunks)}")
        print(f"Найдено triplet'ов: {len(triplets)}")
        print(f"\nОтвет:\n{answer}\n")
        print("Источники:")
        for s in sources:
            print(f"  - {s['source']} / {s['section']} (dist={s['distance']:.4f})")

    return {
        "answer": answer,
        "sources": sources,
        "context": full_context,
        "graph_triplets": triplets,
        "query_entities": query_entities,
        "candidate_articles": candidate_articles,
    }


