def summarize_with_retry(text, max_retries=3):
    for attempt in range(max_retries):
        try:
            response = summary_chain.invoke({"context": text})
            return response.content.strip()
        except Exception as e:
            err_msg = str(e).lower()
            wait = 10 if "rate" in err_msg or "429" in err_msg else 2 ** (attempt + 1)
            print(f"  Ошибка пересказа: {e}. Жду {wait} сек, попытка {attempt + 1}/{max_retries}")
