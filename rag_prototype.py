def find_relevant_summaries(theme, top_k=5):
    embedder = get_embedder()
    theme_emb = embedder.encode(f"query: {theme}", normalize_embeddings=True)

    summaries = []
    for node_id, data in graph.nodes(data=True):
        if data.get("type") != "Summary":
            continue
        summary_text = data.get("text", "")
        if not summary_text:
            continue
        summaries.append({
            "node_id": node_id,
            "text": summary_text,
            "source": data.get("source"),
            "part_index": data.get("part_index"),
        })

    if not summaries:
        return []

    # эмбеддим все пересказы пакетно, это быстрее, чем по одному
    summary_embs = embedder.encode(
        [f"passage: {s['text']}" for s in summaries],
        normalize_embeddings=True,
    )

    import numpy as np
    sims = np.dot(summary_embs, theme_emb)
    for s, sim in zip(summaries, sims):
        s["distance"] = float(1.0 - sim)

    summaries.sort(key=lambda x: x["distance"])
    return summaries[:top_k]


# описание предметной области, собирает обогащённый контекст по теме и просит LLM сформировать
    """
    Контекст склеивается из трёх источников:
      - Summary-узлы графа (плотная смысловая информация)
      - triplet'ы semantic_link, найденные через сущности темы
      - текстовые чанки из vector search

    Top_k намеренно больше, чем в hybrid_rag: описание домена - задача более широкая, чем точечный вопрос
    """
def describe_domain(theme, top_k_vec=8, top_k_graph=10, top_k_summary=5, verbose=True):

    # чанки по теме
    chunks = vector_search(theme, top_k=top_k_vec)

    # сущности из темы и триплеты
    theme_entities, _ = extract_query_entities(theme)
    triplets = find_graph_triplets(theme_entities, max_triplets=top_k_graph)

    # релевантные пересказы
    summaries = find_relevant_summaries(theme, top_k=top_k_summary)

    # сборка контекста: саммари -> триплеты -> чанки
    # саммари идут первыми, потому что они компактны и дают общую картину
    parts_of_context = []

    if summaries:
        sum_block = "[Summaries of relevant article parts:]\n"
        for s in summaries:
            sum_block += f"  - ({s['source']}, part {s['part_index']}) {s['text']}\n"
        parts_of_context.append(sum_block)

    graph_block = format_graph_triplets(triplets)
    if graph_block:
        parts_of_context.append(graph_block)

    if chunks:
        parts_of_context.append(format_context(chunks))

    full_context = "\n\n".join(parts_of_context)

    # запрос к LLM
    if not full_context.strip():
        description = "The indexed materials do not contain sufficient information about this theme."
    else:
        response = domain_chain.invoke({"theme": theme, "context": full_context})
        description = response.content.strip()

    # источники - уникальные статьи, попавшие в контекст
    sources_set = set()
    for c in chunks:
        sources_set.add(c["metadata"]["source"])
    for s in summaries:
        sources_set.add(s["source"])
    sources = sorted(sources_set)

    if verbose:
        print(f"Тема: {theme}\n")
        print(f"Сущности из темы ({len(theme_entities)}): {theme_entities}")
        print(f"Найдено пересказов: {len(summaries)}")
        print(f"Найдено triplet'ов: {len(triplets)}")
        print(f"Найдено чанков: {len(chunks)}")
        print(f"\n--- Описание предметной области ---\n{description}\n")
        print(f"Источники: {sources}")

    return {
        "description": description,
        "sources": sources,
        "triplets": triplets,
        "summaries_used": [s["node_id"] for s in summaries],
    }


