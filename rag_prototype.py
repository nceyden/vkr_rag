def judge_call(prompt, max_retries=3): # один вызов судьи с retry, возвращает текст ответа или ''
    for attempt in range(max_retries):
        try:
            return judge_llm.invoke(prompt).content.strip()
        except Exception as e:
            print(f"    судья ошибка: {e}")
            time.sleep(5)
    return ""


# Faithfulness
def metric_faithfulness(answer, context):
    # шаг 1 разбиваем ответ на утверждения
    p1 = (
        "Break the following ANSWER into a list of separate, simple factual "
        "statements. Output each statement on its own line, nothing else.\n\n"
        f"ANSWER:\n{answer}"
    )
    raw = judge_call(p1)
    statements = [s.strip(" -•*\t0123456789.") for s in raw.split("\n") if s.strip()]
    if not statements:
        return None

    # шаг 2 проверка, просим строго формат "номер: VERDICT"
    numbered = "\n".join(f"{i+1}. {s}" for i, s in enumerate(statements))
    p2 = (
        "Given the CONTEXT, for each numbered STATEMENT decide if it can be "
        "inferred from the context.\n"
        "Reply with ONE line per statement in EXACTLY this format:\n"
        "<number>: SUPPORTED   or   <number>: NOT_SUPPORTED\n"
        "Output nothing else, no explanations.\n\n"
        f"CONTEXT:\n{context}\n\nSTATEMENTS:\n{numbered}"
    )
    verdict = judge_call(p2)

    # парсим построчно ищем SUPPORTED / NOT_SUPPORTED по каждому номеру
    supported = 0
    parsed = 0
    for line in verdict.split("\n"):
        up = line.upper()
        if "NOT_SUPPORTED" in up:
            parsed += 1
        elif "SUPPORTED" in up:
            supported += 1
            parsed += 1
    # если не распарсили ни одной строки - это сбой, возвращаем None, чтобы вопрос не утянул среднее в 0
    if parsed == 0:
        return None
    return supported / parsed


# Answer Relevancy
# алгоритм: ллм генерирует n вопросов из ответа, балл = средняя косинусная близость к реальному вопросу
def metric_answer_relevancy(answer, question, n=3):
    p = (
        f"Based ONLY on the following ANSWER, generate {n} different questions "
        f"that this answer would correctly address. Output each question on its "
        f"own line, nothing else.\n\nANSWER:\n{answer}"
    )
    raw = judge_call(p)
    gen_questions = [q.strip(" -•*\t0123456789.") for q in raw.split("\n") if q.strip()]
    if not gen_questions:
        return None

    # эмбеддинги. реальный вопрос и сгенерированные вопросы
    q_emb = embedder.encode(f"query: {question}", normalize_embeddings=True)
    gen_embs = embedder.encode(
        [f"query: {q}" for q in gen_questions], normalize_embeddings=True
    )
    # косинусная близость = скалярное произведение нормированных векторов
    sims = np.dot(gen_embs, q_emb)
    return float(np.mean(sims))


# Context Relevance
# упрощённый context precision: доля предложений контекста, релевантных вопросу
def metric_context_relevance(question, context):
    p = (
        "Given the QUESTION and the CONTEXT, estimate what fraction of the "
        "context is actually relevant for answering the question. "
        "Return ONLY a number from 0.0 (nothing relevant) to 1.0 (all relevant).\n\n"
        f"QUESTION:\n{question}\n\nCONTEXT:\n{context}"
    )
    raw = judge_call(p)
    m = re.search(r"(\d+\.?\d*)", raw)
    if not m:
        return None
    val = float(m.group(1))
    if val > 1.0:
        val = val / 100.0
    return max(0.0, min(1.0, val))


# Answer Correctness
# сверка фактов ответа с эталонным ответом (ground truth)
def metric_answer_correctness(answer, ground_truth):
    p = (
        "Compare the ANSWER with the reference GROUND TRUTH. Rate how factually "
        "consistent the answer is with the ground truth, considering both "
        "correctness and completeness.\n"
        "Reply with EXACTLY one line in this format:\n"
        "SCORE: <number from 0.0 to 1.0>\n"
        "Output nothing else.\n\n"
        f"GROUND TRUTH:\n{ground_truth}\n\nANSWER:\n{answer}"
    )
    raw = judge_call(p)
    # Ищем число после слова SCORE
    m = re.search(r"SCORE:\s*(\d+\.?\d*)", raw, re.IGNORECASE)
    if not m:
        # запасной вариант — любое число в ответе
        m = re.search(r"(\d+\.?\d*)", raw)
    if not m:
        return None  # не распарсили — None, а не 0.0
    val = float(m.group(1))
    if val > 1.0:
        val = val / 100.0
    return max(0.0, min(1.0, val))


# оценка одного ретривера, возвращает средние по метрикам, список построчных результатов
def evaluate_mode(results, mode):
    print(f"\n--- Оценка: {mode} ---")
    metric_names = ["faithfulness", "answer_relevancy",
                    "context_relevance", "answer_correctness"]
    scores = {m: [] for m in metric_names}
    per_question = []

    for i, r in enumerate(results, start=1):
        answer = r[f"{mode}_answer"]
        context = "\n\n".join(r[f"{mode}_context"])
        question = r["question"]
        gt = r["ground_truth"]

        row = {"category": r["category"]}
        row["faithfulness"] = metric_faithfulness(answer, context)
        row["answer_relevancy"] = metric_answer_relevancy(answer, question)
        row["context_relevance"] = metric_context_relevance(question, context)
        row["answer_correctness"] = metric_answer_correctness(answer, gt)

        for m in metric_names:
            if row[m] is not None:
                scores[m].append(row[m])
        per_question.append(row)
        print(f"  [{i}/{len(results)}] оценён")
        time.sleep(0.3)

    averages = {m: (sum(v) / len(v) if v else 0.0) for m, v in scores.items()}
    return averages, per_question


