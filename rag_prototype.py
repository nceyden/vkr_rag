RAG_PROMPT = ChatPromptTemplate.from_template(
    """You are an assistant for question-answering over a corpus of scientific articles.

Answer the user's question using ONLY the provided context below.
If the context does not contain the answer, reply exactly:
"I could not find the answer in the indexed materials."

Do not use any prior knowledge outside the context.
Do not invent facts, numbers, citations, or author names.
Answer in the same language as the question.

Context:
{context}

Question: {question}

Answer:"""
)

llm_for_qa = get_llm(temperature=0.0)
rag_chain = RAG_PROMPT | llm_for_qa


def format_context(chunks):
    blocks = []
    for i, ch in enumerate(chunks):
        meta = ch["metadata"]
        source = meta.get("source", "unknown")
        heading = meta.get("part_heading", "")
        block = f"[Source {i+1}: {source} | Section: {heading}]\n{ch['text']}"
        blocks.append(block)
    return "\n\n---\n\n".join(blocks)

    """
    Базовый RAG-пайплайн без графа:
      1) векторный поиск top_k чанков
      2) склейка в контекст
      3) генерация ответа LLM с запретом выходить за пределы контекста

    Возвращает dict:
      answer  - строка ответа
      sources - список метаданных использованных чанков
      context - собранный контекст (для отладки и оценки в 3 разделе вкр)
    """
def vanilla_rag(question, top_k=TOP_K_VECTOR, verbose=True):
    # 1 поиск релевантных чанков
    chunks = vector_search(question, top_k=top_k)
    if not chunks:
        return {
            "answer": "I could not find the answer in the indexed materials.",
            "sources": [],
            "context": "",
        }

    # 2 сборка контекста
    context = format_context(chunks) # собранный контекст (для отладки и оценки на этапе тестирования в вкр)

    # 3 запрос к LLM
    response = rag_chain.invoke({"context": context, "question": question})
    answer = response.content.strip()

    sources = [] # источники уникальные пары (статья, раздел)
    seen = set()
    for ch in chunks:
        key = (ch["metadata"]["source"], ch["metadata"]["part_heading"])
        if key not in seen:
            seen.add(key)
            sources.append({
                "source": ch["metadata"]["source"],
                "section": ch["metadata"]["part_heading"],
                "distance": ch["distance"],
            })

    if verbose:
        print(f"Вопрос: {question}\n")
        print(f"Ответ:\n{answer}\n")
        print("Источники:")
        for s in sources:
            print(f"  - {s['source']} / {s['section']} (dist={s['distance']:.4f})")

    return {"answer": answer, "sources": sources, "context": context}


