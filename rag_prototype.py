# индексация
def index_article(article, source_filename):
    chunks = chunk_article(article, source_filename)
    if not chunks:
        print(f"Статья {source_filename} не дала ни одного чанка")
        return 0

    embedder = get_embedder()
    texts_for_embedding = [f"passage: {c['text']}" for c in chunks] # добавбляем passage для лучшей индексации
    embeddings = embedder.encode(
        texts_for_embedding,
        show_progress_bar=True,
        normalize_embeddings=True,  # нормализуем для косинусной метрики
    ).tolist()

    collection.upsert(
        ids=[c["chunk_id"] for c in chunks],
        embeddings=embeddings,
        documents=[c["text"] for c in chunks],
        metadatas=[c["metadata"] for c in chunks],
    )
    return len(chunks)


# поиск в ChromaDB
def vector_search(query, top_k=TOP_K_VECTOR):
    embedder = get_embedder()
    query_embedding = embedder.encode(
        f"query: {query}",  # query для лучшего поиска
        normalize_embeddings=True,
    ).tolist()

    results = collection.query(
        query_embeddings=[query_embedding],
        n_results=top_k,
    )

    # распаковка в удобный формат
    found = []
    for i in range(len(results["ids"][0])):
        found.append({
            "text": results["documents"][0][i],
            "metadata": results["metadatas"][0][i],
            "distance": results["distances"][0][i],
        })
    return found


