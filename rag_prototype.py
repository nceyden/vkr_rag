def extract_query_entities(question): # извлекает сущности и связи из вопроса через LLMGraphTransformer
    doc = Document(page_content=question)
    try:
        graph_docs = graph_transformer.convert_to_graph_documents([doc])
    except Exception as e:
        print(f"  Не удалось извлечь сущности из запроса: {e}")
        return [], []
    if not graph_docs:
        return [], []
    entity_names = [str(n.id).lower().strip() for n in graph_docs[0].nodes]
    query_rels = [
        (str(r.source.id).lower().strip(), r.type, str(r.target.id).lower().strip())
        for r in graph_docs[0].relationships
    ]
    return entity_names, query_rels


def find_graph_triplets(query_entities, max_triplets=TOP_K_GRAPH): # ищет в графе semantic_link, похожие на сущности запроса
    if not query_entities:
        return []
    triplets = []
    for u, v, edge_data in graph.edges(data=True):
        if edge_data.get("type") != "semantic_link":
            continue
        u_name = graph.nodes[u].get("name", "").lower()
        v_name = graph.nodes[v].get("name", "").lower()
        match = False
        for q_ent in query_entities:
            if not q_ent:
                continue
            if (q_ent in u_name or u_name in q_ent or
                q_ent in v_name or v_name in q_ent):
                match = True
                break
        if match:
            triplets.append({
                "source": graph.nodes[u].get("name", u),
                "label": edge_data.get("label", "related_to"),
                "target": graph.nodes[v].get("name", v),
                "source_part": edge_data.get("source_part"),
            })
    seen = set()
    unique = []
    for t in triplets:
        key = (t["source"], t["label"], t["target"])
        if key not in seen:
            seen.add(key)
            unique.append(t)
    return unique[:max_triplets]


def format_graph_triplets(triplets): # форматирует triplet'ы графа в текстовый блок для промпта
    if not triplets:
        return ""
    lines = ["[Knowledge graph relations:]"]
    for t in triplets:
        lines.append(f"  - {t['source']} --[{t['label']}]--> {t['target']}")
    return "\n".join(lines)

