# retry с экспоненциальной задержкой на случай rate limit от Groq
def extract_entities_with_retry(text, max_retries=3):
    doc = Document(page_content=text)
    for attempt in range(max_retries):
        try:
            graph_docs = graph_transformer.convert_to_graph_documents([doc])
            if graph_docs:
                return graph_docs[0].nodes, graph_docs[0].relationships
            return [], []
        except Exception as e:
            err_msg = str(e).lower()
            # rate limit от Groq - ждём дольше
            wait = 10 if "rate" in err_msg or "429" in err_msg else 2 ** (attempt + 1)
            print(f"  Ошибка извлечения сущностей: {e}. Жду {wait} сек, попытка {attempt + 1}/{max_retries}")
            time.sleep(wait)
    print(f"  Не удалось извлечь сущности после {max_retries} попыток, пропускаю")
    return [], []


# построение графа для одной статьи
def build_article_graph(article, source_filename, min_part_length=200):
    article_id = f"Article::{source_filename}"

    # очистка следов предыдущей индексации этой статьи, собираем узлы статьи: сам Article + все её ArticlePart + Summary
    nodes_to_remove = [article_id]
    for n, d in list(graph.nodes(data=True)):
        if d.get("source") == source_filename and d.get("type") in ("ArticlePart", "Summary"):
            nodes_to_remove.append(n)
    # удаление узла автоматически удаляет все инцидентные ему связи
    for n in nodes_to_remove:
        if graph.has_node(n):
            graph.remove_node(n)
    # Удаляем «осиротевшие» связи author_of/article_has_keyword,
    # которые вели к уже удалённому Article (на случай, если узел
    # Author/Keyword остался от других статей)
    # — они и так удалились вместе с article_id, отдельная чистка не нужна.

    # построение заново
    graph.add_node(article_id, type="Article", title=article["title"], source=source_filename)

    for author_name in article["authors"]:
        author_id = f"Author::{author_name}"
        graph.add_node(author_id, type="Author", name=author_name)
        graph.add_edge(author_id, article_id, type="author_of")

    for kw in article["keywords"]:
        kw_id = f"Keyword::{kw}"
        graph.add_node(kw_id, type="Keyword", name=kw)
        graph.add_edge(article_id, kw_id, type="article_has_keyword")

    prev_part_id = None
    for part_idx, part in enumerate(article["parts"]):
        part_id = f"ArticlePart::{source_filename}::{part_idx}"
        graph.add_node(
            part_id, type="ArticlePart",
            heading=part["heading"], part_index=part_idx, source=source_filename,
        )
        graph.add_edge(part_id, article_id, type="part_of")
        if prev_part_id is not None:
            graph.add_edge(part_id, prev_part_id, type="previous_part")
        prev_part_id = part_id

        if len(part["text"]) < min_part_length:
            continue
        print(f"  [{part_idx}] {part['heading'][:50]}: извлекаю сущности...")
        nodes, relationships = extract_entities_with_retry(part["text"])

        for node in nodes:
            entity_id = f"Entity::{str(node.id).lower().strip()}"
            if not graph.has_node(entity_id):
                graph.add_node(
                    entity_id, type="Entity",
                    name=str(node.id), entity_label=getattr(node, "type", "Unknown"),
                )
            graph.add_edge(entity_id, part_id, type="mentioned_in")

        for rel in relationships:
            src_id = f"Entity::{str(rel.source.id).lower().strip()}"
            tgt_id = f"Entity::{str(rel.target.id).lower().strip()}"
            if graph.has_node(src_id) and graph.has_node(tgt_id):
                graph.add_edge(
                    src_id, tgt_id, type="semantic_link",
                    label=rel.type, source_part=part_id,
                )

    print(f"Статья обработана. Граф: {graph.number_of_nodes()} узлов, {graph.number_of_edges()} связей")


def save_graph():
    with open(GRAPH_PATH, "wb") as f:
        pickle.dump(graph, f)
