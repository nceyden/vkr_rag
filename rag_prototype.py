def graph_summary():
    from collections import Counter
    node_types = Counter(d.get("type", "?") for _, d in graph.nodes(data=True))
    edge_types = Counter(d.get("type", "?") for _, _, d in graph.edges(data=True))
    print(f"\nУзлов всего: {graph.number_of_nodes()}")
    for t, c in node_types.most_common():
        print(f"  {t}: {c}")
    print(f"Связей всего: {graph.number_of_edges()}")
    for t, c in edge_types.most_common():
        print(f"  {t}: {c}")


