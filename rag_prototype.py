# парсинг pdf через GROBID и разбор TEI в dict

import requests
import time
from bs4 import BeautifulSoup

# PDF -> GROBID
def parse_pdf_with_grobid(pdf_path, grobid_url=GROBID_URL, max_retries=3):
    endpoint = f"{grobid_url}/api/processFulltextDocument"
    last_error = None

    for attempt in range(max_retries):
        try:
            with open(pdf_path, "rb") as f:
                response = requests.post(
                    endpoint,
                    files={"input": f},
                    timeout=180,
                )
            # 200 и 206 оба считаем успехом, если тело похоже на TEI
            if response.status_code in (200, 206):
                text = response.text
                if "<TEI" in text and "<body" in text:
                    return text
                elif "Preparing Space" in text or "<!DOCTYPE html>" in text[:200]:
                    last_error = (
                        "GROBID Space спит или перегружен (HF возвращает HTML-заглушку). "
                        "Попробуй через несколько минут или смени GROBID_URL на резервный Space."
                    )
                    print(last_error)
                else:
                    last_error = f"Статус {response.status_code}, но тело не содержит TEI (длина {len(text)})"
                    print(last_error)

        except requests.exceptions.RequestException as e:
            last_error = f"Ошибка сети: {e}"
            print(f"{last_error}, попытка {attempt + 1}/{max_retries}")

        # экспоненциальная задержка 2 4 8 с
        if attempt < max_retries - 1:
            time.sleep(2 ** (attempt + 1))

    raise RuntimeError(f"Не удалось получить TEI от GROBID после {max_retries} попыток. Последняя ошибка: {last_error}")


# TEI -> dict
    """
      title: str
      authors: list[str]
      keywords: list[str]
      parts: list[dict] - каждая часть имеет поля 'heading' и 'text'

    "Часть статьи" в терминологии ТЗ - это заголовок любого уровня
    и весь текст до следующего заголовка. Иерархия не сохраняется,
    только порядок следования (это важно для previous_part связей в графе)
    """
def tei_to_dict(tei_xml):

    soup = BeautifulSoup(tei_xml, "lxml-xml")

    title_tag = soup.find("titleStmt")
    title = ""
    if title_tag and title_tag.find("title"):
        title = title_tag.find("title").get_text(strip=True)

    authors = []
    source_desc = soup.find("sourceDesc")
    if source_desc:
        for author_tag in source_desc.find_all("author"):
            pers_name = author_tag.find("persName")
            if pers_name:
                forenames = [fn.get_text(strip=True) for fn in pers_name.find_all("forename")]
                surnames = [sn.get_text(strip=True) for sn in pers_name.find_all("surname")]
                full_name = " ".join(forenames + surnames).strip()
                if full_name:
                    authors.append(full_name)

    keywords = []
    keywords_tag = soup.find("keywords")
    if keywords_tag:
        terms = keywords_tag.find_all("term")
        if terms:
            keywords = [t.get_text(strip=True) for t in terms if t.get_text(strip=True)]
        else:
            # Fallback: текст через запятую или точку с запятой
            raw = keywords_tag.get_text(strip=True)
            if raw:
                keywords = [k.strip() for k in raw.replace(";", ",").split(",") if k.strip()]

    # тело - <body>, внутри него <div> для каждого раздела
    # в каждом <div> есть <head> (заголовок) и несколько <p>
    # плюс добавляем abstract как первую часть, если он есть
    parts = []

    abstract_tag = soup.find("abstract")
    if abstract_tag:
        abstract_text = " ".join(p.get_text(" ", strip=True) for p in abstract_tag.find_all("p"))
        if abstract_text:
            parts.append({"heading": "Abstract", "text": abstract_text})

    body = soup.find("body")
    if body:
        for div in body.find_all("div", recursive=False):
            head_tag = div.find("head")
            heading = head_tag.get_text(strip=True) if head_tag else "(без заголовка)"

            # собираем все параграфы
            paragraphs = [p.get_text(" ", strip=True) for p in div.find_all("p")]
            text = "\n\n".join(p for p in paragraphs if p)

            if text:  # скип пустых разделов
                parts.append({"heading": heading, "text": text})

    return {
        "title": title,
        "authors": authors,
        "keywords": keywords,
        "parts": parts,
    }


