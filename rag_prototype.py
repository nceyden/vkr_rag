import chromadb
from sentence_transformers import SentenceTransformer
from langchain_text_splitters import RecursiveCharacterTextSplitter

# ленивая загрузка эммбедера
_embedder = None

def get_embedder():
    global _embedder
    if _embedder is None:
        print(f"Загружаю модель {EMBEDDING_MODEL} (первый раз ~2 мин)...")
        _embedder = SentenceTransformer(EMBEDDING_MODEL)
        print("Модель загружена")
    return _embedder


# чанкинг статьи
def chunk_article(article, source_filename):
    splitter = RecursiveCharacterTextSplitter(
        chunk_size=CHUNK_SIZE,
        chunk_overlap=CHUNK_OVERLAP,
        separators=["\n\n", "\n", ". ", " ", ""],
    )

    chunks = []
    for part_idx, part in enumerate(article["parts"]):
        part_chunks = splitter.split_text(part["text"])
        for chunk_idx, chunk_text in enumerate(part_chunks):
            chunk_id = f"{source_filename}::part{part_idx}::chunk{chunk_idx}"
            chunks.append({
                "text": chunk_text,
                "chunk_id": chunk_id,
                "metadata": {
                    "source": source_filename,
                    "title": article["title"],
                    "part_index": part_idx,
                    "part_heading": part["heading"],
                    "chunk_index": chunk_idx,
                },
            })
    return chunks


