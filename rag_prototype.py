# функция-обёртка для q&a
def ui_qa(question, mode):
    """Обёртка над vanilla_rag / hybrid_rag для UI Gradio."""
    if not question or not question.strip():
        return "Введи вопрос", ""
    if collection.count() == 0:
        return "В базе нет ни одной статьи. Сначала проиндексируй PDF на вкладке 'Индексация'.", ""
    fn = hybrid_rag if mode == "Hybrid (с графом)" else vanilla_rag
    result = fn(question.strip(), verbose=False)
    sources_md = "**Источники:**\n"
    for s in result["sources"]:
        sources_md += f"- `{s['source']}` / *{s['section']}* (dist={s['distance']:.3f})\n"
    if mode == "Hybrid (с графом)" and result.get("graph_triplets"):
        sources_md += "\n**Связи из графа:**\n"
        for t in result["graph_triplets"]:
            sources_md += f"- `{t['source']}` —[**{t['label']}**]→ `{t['target']}`\n"
    return result["answer"], sources_md


